/* ── Resizable right panel (drag the divider) ──
   Panel width is capped at 300px minimum and, so the asset table always
   keeps at least half the page, half of the tab's current width maximum
   (falling back to a flat 760px cap when the tab is hidden and has no
   measurable width, e.g. on initial page load). */
(function() {
  const rz  = document.getElementById('rpResizer');
  const tab = document.getElementById('tab-register');
  if (!rz || !tab) return;

  function maxPanelW() {
    const w = tab.getBoundingClientRect().width;
    return w > 0 ? Math.min(760, Math.round(w / 2)) : 760;
  }
  function applyWidth(w) {
    const clamped = Math.min(maxPanelW(), Math.max(300, Math.round(w)));
    tab.style.gridTemplateColumns = '1fr 6px ' + clamped + 'px';
  }

  let saved = null;
  try { saved = parseInt(localStorage.getItem('r8-rp-w'), 10) || null; } catch(e) {}
  if (saved) applyWidth(saved);

  // Re-clamp once the register tab becomes visible and its real width is
  // known (getBoundingClientRect reads 0 while display:none).
  window.reclampAssetPanel = function() {
    const right = document.querySelector('#tab-register .right');
    if (right) applyWidth(right.getBoundingClientRect().width);
  };

  let dragging = false;
  rz.addEventListener('pointerdown', function(e) {
    e.preventDefault();
    dragging = true;
    rz.classList.add('dragging');
    document.body.style.userSelect = 'none';
    document.body.style.cursor = 'col-resize';
  });
  window.addEventListener('pointermove', function(e) {
    if (!dragging) return;
    applyWidth(tab.getBoundingClientRect().right - e.clientX);
  });
  function endDrag() {
    if (!dragging) return;
    dragging = false;
    rz.classList.remove('dragging');
    document.body.style.userSelect = '';
    document.body.style.cursor = '';
    const right = document.querySelector('#tab-register .right');
    if (right) { try { localStorage.setItem('r8-rp-w', Math.round(right.getBoundingClientRect().width)); } catch(e) {} }
  }
  window.addEventListener('pointerup', endDrag);
  window.addEventListener('pointercancel', endDrag);
  window.addEventListener('blur', endDrag);
  window.addEventListener('resize', function() {
    if (tab.offsetParent !== null) window.reclampAssetPanel();
  });
})();

