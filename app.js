/* ── Document Repository ─────────────────────────────────────── */
(function(){
  var _files = [];

  function fmtDate(d){ if(!d) return ''; var p=d.split('-'); return p[2]+'/'+p[1]+'/'+p[0].slice(2); }

  var ICO_FILE = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"><path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/><path d="M14 2v6h6"/></svg>';
  var ICO_FOLDER = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"><path d="M3 7a2 2 0 0 1 2-2h4l2 2h8a2 2 0 0 1 2 2v8a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2z"/></svg>';
  var ICO_DOWNLOAD = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M12 3v12m0 0 4-4m-4 4-4-4"/><path d="M4 17v2a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2v-2"/></svg>';

  function fileRow(f){
    var h = '<div class="repo-file-row">';
    h += '<span class="rfile-ico">'+ICO_FILE+'</span>';
    h += '<div class="rfile-info">';
    h += '<div class="rfile-title">'+f.title+'</div>';
    h += '<div class="rfile-meta"><span class="rfile-fname">'+f.filename+'</span></div>';
    h += '</div>';
    h += '<div class="rfile-right">';
    h += '<span class="rfile-size">'+f.size+'</span>';
    h += '<span class="rfile-date">'+fmtDate(f.date)+'</span>';
    h += '<a href="'+encodeFilePath(f.path)+'" target="_blank" class="rfile-btn rfile-view">View</a>';
    h += '<a href="'+encodeFilePath(f.path)+'" download class="rfile-btn rfile-dl">'+ICO_DOWNLOAD+'</a>';
    h += '</div></div>';
    return h;
  }

  function buildPathTree(files, query){
    // Build { topFolder: { _direct: [files], subName: [files] } }
    var q = (query||'').toLowerCase().trim();
    var tree = {};
    var order = [];
    files.forEach(function(f){
      var matches = !q ||
        (f.title||'').toLowerCase().indexOf(q)>=0 ||
        (f.filename||'').toLowerCase().indexOf(q)>=0 ||
        (f.description||'').toLowerCase().indexOf(q)>=0;
      if(!matches) return;
      // Strip leading 'Reports/' prefix then split
      var rel = f.path.replace(/^Reports\//, '');
      var parts = rel.split('/');
      var top = parts[0];
      var subs = parts.slice(1, -1); // intermediate folder(s), if any
      if(!tree[top]){ tree[top] = { _direct: [] }; order.push(top); }
      if(subs.length === 0){
        if(!f._empty) tree[top]._direct.push(f);
      } else {
        var subKey = subs.join('/');
        if(!tree[top][subKey]) tree[top][subKey] = [];
        tree[top][subKey].push(f);
      }
    });
    return { tree: tree, order: order };
  }

  function renderTree(files, query){
    var result = buildPathTree(files, query);
    var tree = result.tree, order = result.order;
    var html = '';
    order.forEach(function(top){
      var node = tree[top];
      var subKeys = Object.keys(node).filter(function(k){ return k !== '_direct'; });
      var totalFiles = node._direct.length + subKeys.reduce(function(s,k){ return s+node[k].length; },0);
      html += '<div class="repo-folder">';
      // Empty folders still render — count badge shows '0 files' with muted style
      html += '<div class="repo-folder-hd" onclick="repoToggle(this)">';
      html += '<span class="rf-chevron">&#9660;</span>';
      html += '<span class="rf-ico">'+ICO_FOLDER+'</span>';
      html += '<span class="rf-name">'+top+'</span>';
      var countLabel = totalFiles === 0
        ? '<span class="rf-count" style="opacity:0.45">empty</span>'
        : '<span class="rf-count">'+totalFiles+' file'+(totalFiles!==1?'s':'')+'</span>';
      html += countLabel;
      html += '</div>';
      html += '<div class="repo-folder-body">';
      // Direct files first
      if(node._direct.length === 0 && subKeys.length === 0) {
        html += '<div style="padding:18px 24px;font-family:var(--font);font-size:13px;color:var(--ink-4);font-style:italic">No documents yet — files added to this folder will appear here.</div>';
      }
      node._direct.forEach(function(f){ html += fileRow(f); });
      // Subfolders
      subKeys.forEach(function(sub){
        var subFiles = node[sub];
        html += '<div class="repo-subfolder">';
        html += '<div class="repo-subfolder-hd" onclick="repoToggle(this)">';
        html += '<span class="rf-chevron">&#9660;</span>';
        html += '<span class="rf-ico">'+ICO_FOLDER+'</span>';
        html += '<span class="rf-name">'+sub+'</span>';
        html += '<span class="rf-count">'+subFiles.length+' file'+(subFiles.length!==1?'s':'')+'</span>';
        html += '</div>';
        html += '<div class="repo-folder-body repo-subfolder-body">';
        subFiles.forEach(function(f){ html += fileRow(f); });
        html += '</div></div>';
      });
      html += '</div></div>';
    });
    if(!html) html = '<div class="repo-no-results">No documents match &ldquo;'+query+'&rdquo;</div>';
    document.getElementById('repo-tree').innerHTML = html;
  }

  function encodeFilePath(path){
    return path.split('/').map(function(seg){ return encodeURIComponent(seg); }).join('/');
  }

  window.repoFilter = function(val){ renderTree(_files, val); };

  window.repoToggle = function(hd){
    var body = hd.nextElementSibling;
    var chev = hd.querySelector('.rf-chevron');
    if(body.style.display==='none'){
      body.style.display=''; chev.classList.remove('closed');
    } else {
      body.style.display='none'; chev.classList.add('closed');
    }
  };

  function parseMB(s){
    if(!s) return 0;
    var n=parseFloat(s), u=s.toUpperCase();
    if(u.indexOf('MB')>=0||u.indexOf('M ')>=0||u.slice(-1)==='M') return n;
    if(u.indexOf('KB')>=0||u.indexOf('K ')>=0||u.slice(-1)==='K') return n/1024;
    return n;
  }

  function loadReports(){
    fetchJSON('Reports/index.json')
      .then(function(files){
        _files = files;
        renderTree(files);
        var total = files.reduce(function(s,f){ return s+parseMB(f.size); },0);
        document.getElementById('repo-file-count').textContent = files.length+' document'+(files.length!==1?'s':'');
        document.getElementById('repo-total-size').textContent = total.toFixed(1)+' MB total';
      })
      .catch(function(){
        document.getElementById('repo-tree').innerHTML =
          '<div class="repo-empty">Could not load document index.</div>';
      });
  }

  // Load when Reports tab is opened
  var _repoLoaded = false;
  var _origSetNav = window.setNav;
  document.addEventListener('DOMContentLoaded', function(){
    // Patch setNav to trigger load on first Reports open
    var origSN = window.setNav;
    window.setNav = function(el){
      origSN(el);
      if(el && el.dataset && el.dataset.tab==='reports' && !_repoLoaded){
        _repoLoaded = true; loadReports();
      }
    };
    // Also handle direct link from home nav cards
    document.querySelectorAll('[onclick]').forEach(function(el){
      var oc = el.getAttribute('onclick');
      if(oc && oc.indexOf('tab=reports')>=0 || (oc && oc.indexOf("'reports'")>=0)){
        // handled by setNav patch above
      }
    });
  });
})();


