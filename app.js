/* ── Construction Waste is a separate material stream (tracked outside the fitout defit dataset).
   Assets flagged excludeFromStats in assets.json (e.g. Perimeter Blinds, pending base-build confirmation)
   stay in the register but are likewise left out of every total.
   Excluded from every KPI / chart total below; shown only in the ALD Report tab. ── */
function statsAssets() {
  return ASSETS.filter(a => a.cat !== 'Construction Waste' && !a.excluded);
}

/* ── Reported diversion rate: fixed headline with a +/- error derived from the measured rate
   (gap to the measured rate, to the nearest whole %). Measured value stays in computeStats().divRate. ── */
const DIV_RATE_HEADLINE = 95;

/* ── KPI computations (shared) ── */
function computeStats() {
  const stats      = statsAssets();
  const totalKg    = stats.reduce((s,a) => s + (a.kg||0), 0);
  const totalEc    = stats.reduce((s,a) => s + (a.ec||0), 0);
  const totalWaste = stats.reduce((s,a) => s + (a.waste||0), 0);
  const divertKg   = stats.filter(a => a.pw !== 'Dispose').reduce((s,a) => s + (a.kg||0), 0);
  const landfillKg = stats.filter(a => a.pw === 'Dispose').reduce((s,a) => s + (a.kg||0), 0);
  const divRate    = totalKg > 0 ? (divertKg / totalKg * 100) : 0;
  const partners   = new Set(stats.flatMap(a => a.partners)).size;
  const cats       = new Set(stats.map(a => a.cat)).size;
  const retained   = stats.filter(a => a.pw === 'Retain').length;
  const divRateErr = Math.round(Math.abs(divRate - DIV_RATE_HEADLINE));
  return { totalKg, totalEc, totalWaste, divertKg, landfillKg, divRate, divRateErr, partners, cats, retained };
}

/* ── Overview tab KPIs ── */
