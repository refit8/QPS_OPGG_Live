/* ── Active filter chips ── */
function renderChips() {
  const c = document.getElementById('filterChips');
  if (!c) return;
  const chips = [];
  const mk = (group, type, val) =>
    `<span class="f-chip"><b>${group}:</b> ${val}<button onclick="removeFilter('${type}','${encodeURIComponent(val)}')" title="Remove filter">×</button></span>`;
  fpPWs.forEach(v => chips.push(mk('Pathway', 'pw', v)));
  fpCats.forEach(v => chips.push(mk('Category', 'cat', v)));
  fpMats.forEach(v => chips.push(mk('Material', 'mat', v)));
  if (chips.length) chips.push('<span class="f-chip clear" onclick="clearFilters()">Clear all</span>');
  c.innerHTML = chips.join('');
}

function filterSet(type) { return { pw: fpPWs, cat: fpCats, mat: fpMats }[type]; }

function removeFilter(type, encVal) {
  filterSet(type).delete(decodeURIComponent(encVal));
  activeQuickView = 'custom';
  syncQuickView();
  buildFilterPanel();
  doFilter();
}

function clearFilters() {
  fpPWs.clear(); fpCats.clear(); fpMats.clear();
  activeQuickView = 'all';
  syncQuickView();
  buildFilterPanel();
  doFilter();
}

