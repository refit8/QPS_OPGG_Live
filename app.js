/* ── Filtering — one model: checked values = shown values ── */
function doFilter() {
  const q = document.getElementById('srch').value.toLowerCase();
  filtered = ASSETS.filter(a =>
    (a.qty > 0) &&
    (fpPWs.size  === 0 || fpPWs.has(a.pw))   &&
    (fpCats.size === 0 || fpCats.has(a.cat)) &&
    (fpMats.size === 0 || fpMats.has(a.mat)) &&
    (!q ||
      a.n.toLowerCase().includes(q)   ||
      a.mat.toLowerCase().includes(q) ||
      a.cat.toLowerCase().includes(q) ||
      a.pw.toLowerCase().includes(q)  ||
      a.partners.some(p => p.toLowerCase().includes(q)))
  );
  updateFilterBadge();
  syncPillFilters();
  applySort();
}

