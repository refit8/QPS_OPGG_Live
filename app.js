function buildFilterPanel() {
  if (!ASSETS.length) return;
  const build = (elId, values, set, type) => {
    const el = document.getElementById(elId);
    if (!el) return;
    el.innerHTML = values.map(v => `<label class="fp-item">
      <input type="checkbox" ${set.has(v) ? 'checked' : ''} onchange="fpToggle('${type}','${encodeURIComponent(v)}')" />
      <span>${v}</span>
    </label>`).join('');
  };
  build('fp-pw-list',  Object.keys(PW), fpPWs, 'pw');
  build('fp-cat-list', [...new Set(ASSETS.map(a => a.cat).filter(Boolean))].sort(), fpCats, 'cat');
  build('fp-mat-list', [...new Set(ASSETS.map(a => a.mat).filter(Boolean))].sort(), fpMats, 'mat');
}

function fpToggle(type, encVal) {
  const val = decodeURIComponent(encVal);
  const set = filterSet(type);
  set.has(val) ? set.delete(val) : set.add(val);
  activeQuickView = 'custom';
  syncQuickView();
  doFilter();
}

