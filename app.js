function catTag(cat) {
  if (cat === 'Built Form')  return 'builtform';
  if (cat === 'FF&E')        return 'ffe';
  if (cat === 'Services')    return 'services';
  if (cat === 'Construction Waste') return 'tradewaste';
  return 'builtform';
}

/* ── Normalise raw assets.json record → internal shape ── */
function normaliseAsset(r) {
  return {
    id:       r.id,
    n:        r.title,
    imageUrl: r.imageUrl || null,
    thumbUrl: r.thumbUrl || null,
    images:   (r.images && r.images.length) ? r.images : (r.imageUrl ? [r.imageUrl] : []),
    cat:      r.category || '',
    tag:      catTag(r.category),
    pw:       (r.pathway && r.pathway.suggested) || 'Unknown',
    qty:      r.quantity || 0,
    unit:     r.unit || '',
    kg:       (r.weight  && r.weight.total)              || 0,
    mat:      r.primaryMaterialStream                    || '',
    partners: (r.pathway && r.pathway.partners)          || [],
    partnersSupp: (r.pathway && r.pathway.partnersSupplementary) || [],
    ec:       (r.embodiedCarbon && r.embodiedCarbon.total) || 0,
    waste:    (r.wasteEmissions && r.wasteEmissions.potential) || 0,
    audit:    (r.notes  && r.notes.audit)                || null,
    workshop: (r.notes  && r.notes.workshop)             || null,
    loc:      r.location    || null,
    mfr:      r.manufacturer|| null,
    sup:      r.supplier    || null,
    pNotes:   r.pathwayNotes || {},
    confirmed: (typeof r.pathwayConfirmed === 'boolean') ? r.pathwayConfirmed : null,
    reused:   r.intoNewFitout === true,
    excluded: r.excludeFromStats === true,
  };
}

