(function loadRegColOrder() {
  try {
    const saved = JSON.parse(localStorage.getItem(REG_COL_ORDER_KEY));
    if (Array.isArray(saved) && saved.length === REG_COLUMNS.length &&
        REG_COLUMNS.every(c => saved.includes(c.id))) {
      regColOrder = saved;
    }
  } catch(e) {}
})();
function orderedRegColumns() {
  return regColOrder.map(id => REG_COLUMNS.find(c => c.id === id));
}
function renderRegHead() {
  const tr = document.getElementById('regThead');
  if (!tr) return;
  tr.innerHTML = orderedRegColumns().map(c => c.id === 'thumb'
    ? `<th style="width:40px" data-col="thumb"></th>`
    : `<th draggable="true" data-col="${c.id}" onclick="sortBy(${c.sortCol})">${c.label} ↕</th>`
  ).join('');
  let dragId = null;
  tr.querySelectorAll('th[draggable="true"]').forEach(th => {
    th.addEventListener('dragstart', () => {
      dragId = th.dataset.col;
      th.classList.add('dragging-col');
    });
    th.addEventListener('dragend', () => {
      th.classList.remove('dragging-col');
      tr.querySelectorAll('th').forEach(x => x.classList.remove('drag-over-col'));
    });
    th.addEventListener('dragover', e => {
      e.preventDefault();
      if (dragId && th.dataset.col !== dragId) th.classList.add('drag-over-col');
    });
    th.addEventListener('dragleave', () => th.classList.remove('drag-over-col'));
    th.addEventListener('drop', e => {
      e.preventDefault();
      th.classList.remove('drag-over-col');
      const targetId = th.dataset.col;
      if (!dragId || dragId === targetId) return;
      const from = regColOrder.indexOf(dragId);
      const to   = regColOrder.indexOf(targetId);
      regColOrder.splice(from, 1);
      regColOrder.splice(to, 0, dragId);
      try { localStorage.setItem(REG_COL_ORDER_KEY, JSON.stringify(regColOrder)); } catch(e) {}
      dragId = null;
      renderRegHead();
      renderAll();
    });
  });
}
